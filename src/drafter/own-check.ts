// THE GAP'S OWN CHECK, SHOWN READ-ONLY (open copy of the floor's ownCheckGrounding block, ownCheckNamedBodies and
// ownCheckImportsBlock in feature-compose.ts, and retry-evidence's testTitleSegmentOffset). Pure: the check's source
// and the read-only modules' text are facts the closed core read from the vessel clone. Which imports became
// targets and which stayed read-only is a closed decision (the autonomy scope); this file only renders it.
import { renderWindowForDrafter } from "../control-bytes.js";
import type { DrafterFacts } from "./types.js";
import { focusedSlice, PER_FILE_SLICE } from "./windows.js";

/** At most this many read-only modules are shown (the floor's RELOCATION_HINT_MAX_FILES). */
export const READONLY_MODULES_SHOWN = 3;

const TEST_CALL_START_RE = /\n[ \t]*(?:it|test|describe)(?:\.\w+)?\(/;
const TEMPLATE_LITERAL_RE = /`((?:[^`\\]|\\[\s\S])*)`/g;
const PLACEHOLDER_RE = /\$\{[^}]*\}/;
const escapeRegExp = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Where the title segment is written in a test file's source (literally, or as a template whose placeholders
 *  read as wildcards produce the whole segment), or -1. */
export function testTitleSegmentOffset(src: string, segment: string): number {
  const seg = segment.trim();
  if (!seg) return 0;
  const at = src.indexOf(seg);
  if (at >= 0) return at;
  for (const m of src.matchAll(TEMPLATE_LITERAL_RE)) {
    const body = (m[1] ?? "").trim();
    if (!PLACEHOLDER_RE.test(body)) continue;
    const parts = body.split(new RegExp(PLACEHOLDER_RE.source, "g"));
    if (parts.join("").trim().length === 0) continue;
    if (new RegExp(`^${parts.map(escapeRegExp).join("[\\s\\S]*?")}$`).test(seg)) return m.index ?? 0;
  }
  return -1;
}

/** The source of each named test (title line to the next it/test/describe), deduplicated, plus names not found. */
export function ownCheckNamedBodies(source: string, onlyTests: readonly string[]): { bodies: string[]; unlocated: string[] } {
  const starts = new Set<number>();
  const bodies: string[] = [];
  const unlocated: string[] = [];
  for (const name of onlyTests) {
    const leaf = name.split(" > ").pop()?.trim() ?? "";
    const at = leaf ? testTitleSegmentOffset(source, leaf) : -1;
    if (at < 0) { unlocated.push(name); continue; }
    const lineStart = source.lastIndexOf("\n", at) + 1;
    if (starts.has(lineStart)) continue;
    starts.add(lineStart);
    const next = TEST_CALL_START_RE.exec(source.slice(at));
    bodies.push(source.slice(lineStart, next ? at + next.index : source.length).trimEnd());
  }
  return { bodies, unlocated };
}

/** THE GAP'S OWN CHECK block: the whole file when it fits one window, else its imports and the named test bodies. */
export function ownCheckBlock(oc: NonNullable<DrafterFacts["ownCheck"]>): string {
  const source = oc.source;
  let shown: string;
  if (source.length <= PER_FILE_SLICE) shown = source;
  else if (oc.only_tests.length === 0) shown = `${source.slice(0, PER_FILE_SLICE)}\n… (truncated)`;
  else {
    const header = [
      ...[...source.matchAll(/^import\s[\s\S]*?["'][^"'\n]+["'];?[ \t]*$/gm)].map((m) => m[0]),
      ...[...source.matchAll(/^[ \t]*(?:const|let)\b[^\n]*\bawait\s+import\([^\n]*$/gm)].map((m) => m[0]),
    ];
    const { bodies, unlocated } = ownCheckNamedBodies(source, oc.only_tests);
    const text = [header.join("\n"), ...bodies].join("\n…\n")
      + (unlocated.length > 0 ? `\n… (${unlocated.length} named test(s) not located in the file)` : "");
    shown = text.length <= PER_FILE_SLICE ? text : `${text.slice(0, PER_FILE_SLICE)}\n… (truncated)`;
  }
  const what = oc.only_tests.length > 0 ? `its ${oc.only_tests.length} named test(s)` : "this file";
  return `THE GAP'S OWN CHECK — repos/${oc.vessel}/${oc.test_file} (READ-ONLY CONTEXT; NOT A TARGET FILE).\n`
    + `This test is what your draft is judged by: after your change ${what} MUST PASS. Bind the change to the API it calls, the option names it passes and the identifiers it imports. `
    + `Do NOT edit this file or any other test: a draft that edits it is refused, however green it makes the check.\n${renderWindowForDrafter(shown)}`;
}

/** The imported modules: the added targets by name, each read-only module in one window. */
export function ownCheckImportsBlock(input: { added: readonly string[]; readonly: ReadonlyArray<{ path: string; why: string; content: string | null }>; focusHints: readonly string[] }): string {
  const parts: string[] = [];
  if (input.added.length > 0) parts.push(`MODULES THE CHECK IMPORTS, ADDED AS TARGET FILES: ${input.added.join(", ")}. You MAY edit these: they are target files of this compose (TARGET-FILE-SCOPE covers them) and their windows are under GROUND TRUTH above.`);
  for (const r of input.readonly.slice(0, READONLY_MODULES_SHOWN)) {
    const content = r.content ?? "";
    const { slice } = focusedSlice(content, PER_FILE_SLICE, input.focusHints);
    parts.push(`----- ${r.path} (READ-ONLY: the check imports it, but this compose may NOT edit it; excluded from autonomous work by ${r.why}. A change needed here cannot land from this compose: make the fix in a target file.) -----\n`
      + (r.content === null ? "(unreadable)" : renderWindowForDrafter(`${slice}${slice.length < content.length ? "\n… (windowed)" : ""}`)));
  }
  return parts.join("\n\n");
}

/** The own-check section appended after GROUND TRUTH ("" when the gap has no own check). */
export function renderOwnCheck(f: DrafterFacts, focusHints: readonly string[]): string {
  const oc = f.ownCheck;
  if (!oc) return "";
  const importsBlock = ownCheckImportsBlock({
    added: f.targets.ownCheckAdded,
    readonly: f.targets.ownCheckReadonly.map((r) => ({ path: r.path, why: r.why, content: oc.readonlyModules[r.path] ?? null })),
    focusHints,
  });
  return `\n\n${ownCheckBlock(oc)}${importsBlock ? `\n\n${importsBlock}` : ""}`;
}
