// F-ARM: A CHECK THAT NAMES AN EXPORT ITS MODULE DOES NOT HAVE IS REFUSED AT ATTACH.
//
// The supply's check writer drafts a gap's check without the target module's export list. The instance: goal-host
// 2f36f62 landed test/checks/route-edit-bd252f8c.check.ts, which reads `mod["shellResult"]` off src/index.ts and
// asserts typeof "function" before calling it. shellResult is a SHAPE NAME, not an export, so that check is red for
// the invented name on every tree, never for the defect, and the arm step attached it as the gap's falsifier. The
// second known instance: activity-api 7b54fc7 landed a check reading `AuthCache` off src/middleware/auth-cache.ts,
// which exports no such name.
//
// THE CONTRACT (check-supply-admission.ts missingExportRefusal, called by gap-check-supply's arm step before the
// birth verdict): every name the check reads off a src module of its vessel (named import, default import, a member
// of a namespace or dynamic-import binding, through casts) is compared with the module's real exports, parsed from its
// source; the first one missing refuses with `check_references_missing_export:<symbol>`, recorded on the gap's ledger
// (state arm_refused, judged_titles kept for the next attempt) and counted (refused, not_armed). A check whose every
// assertion is existence-only keeps state existence_only (pinned by system-authored-gap-checks) and carries the named
// reason too. Controls: a check on a real export arms as before; a check reading no module member is unaffected; a
// module whose export list cannot be read completely decides nothing.
//
// The two check files are the landed text verbatim; the export surfaces are those of the modules they were written
// against (fixtures beside them, generated by the same extractor from the real files), and a real excerpt of goal-host's
// src/index.ts is a fixture too (goal-host-index.before-2f36f62.excerpt.ts.txt: the file at the parent of 2f36f62, its
// export statements verbatim with bodies elided, read as the same 68 exports as the whole file), so the guard is also
// run over the real source text on every tree, never skipped. Hermetic: temp gap store and clone root, fetch stubbed,
// the birth judge replaced.
