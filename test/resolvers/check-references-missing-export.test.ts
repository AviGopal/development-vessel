/** A gap whose supply goal is in flight, its check file landed in the clone with `text`, then one tick. */
async function landAndTick(prefix: string, vessel: string, editSite: string, text: string): Promise<{ id: string; body: Row }> {
  let id = "";
  for (let i = 0; i < 1000 && !id; i++) { const c = `${prefix}-${RUN}-${i}`; if (supply.checkSupplyArm(c, 0) === "treatment") id = c; }
  const testFile = supply.checkSupplyTestFile(id);
  const now = Date.now();
  const w = await sg.resolveSubstrateGapWrite({ type: "substrateGap_write", gap: { id, category: "systematic_failure", source: "operator", status: "open", detected_at: new Date(now).toISOString(), summary: `${prefix} fixture ${RUN}: repos/${vessel}/${editSite} defect`, classification_metadata: {
    check_supply: { state: "goal_dispatched", attempts: 1, last_dispatch_at: new Date(now - 3600_000).toISOString(), test_file: testFile, vessel, mode: "check_file", baseline_titles: [], edit_site: `repos/${vessel}/${editSite}`, dispatch_id: `d-${id}`, dispatch_node: "substrate" },
  } } } as never);
  if (w.shape === "structuredError") throw new Error("seed refused: " + JSON.stringify(w.body));
  await sg.__settleBirthEvaluationsForTests();
  writeFileSync(join(CLONES, vessel, testFile), text);
  const r = await supply.resolveGapCheckSupplyTick({ type: "gap_check_supply_tick", now_ms: now } as never);
  await sg.__settleBirthEvaluationsForTests();
  return { id, body: r.body as Row };
}

